#!/usr/bin/env node
// Bundles public/js/core.js into the Scriptable widget as a single file:
//   widget/widget.src.js  ->  widget/Box Office Tracker.js
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const root = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const coreSrc = readFileSync(join(root, "public/js/core.js"), "utf8");
const widgetSrc = readFileSync(join(root, "widget/widget.src.js"), "utf8");

const names = [...coreSrc.matchAll(/^export (?:async )?(?:function|const|let) ([A-Za-z_$][\w$]*)/gm)].map((m) => m[1]);
const body = coreSrc.replace(/^export (?=(?:async )?(?:function|const|let) )/gm, "");
if (/^\s*(import|export)\b/m.test(body)) throw new Error("core.js must not import/export anything else");

const coreBlock =
  "// ---- core.js (generated by scripts/build-widget.mjs — edit public/js/core.js instead) ----\n" +
  "const core = (function () {\n" +
  body.replace(/^/gm, "  ") +
  "\n  return { " + names.join(", ") + " };\n})();\n// ---- end core.js ----";

const header =
  "// Variables used by Scriptable.\n" +
  "// These must be at the very top of the file. Do not edit.\n" +
  "// icon-color: deep-gray; icon-glyph: film;\n";

const out = header + "\n" + widgetSrc.replace("/* __CORE__ */", coreBlock);
writeFileSync(join(root, "widget/Box Office Tracker.js"), out);
// Also served by the web app so it can be copied/downloaded straight on the iPhone.
mkdirSync(join(root, "public/widget"), { recursive: true });
writeFileSync(join(root, "public/widget/Box-Office-Tracker.js"), out);
console.log("Built widget/Box Office Tracker.js + public/widget/Box-Office-Tracker.js (" + Math.round(out.length / 1024) + " KB, core exports: " + names.length + ")");
